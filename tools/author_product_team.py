def main() -> None:
    DST.mkdir(parents=True, exist_ok=True)
    for member, (zh, en, marker, body) in BRIEFS.items():
        header = HEADER.format(zh=zh, en=en, member=member, marker=marker)
        out = DST / f"{member}.md"
        out.write_text(header + body.strip() + "\n" + COMMON.strip() + "\n", encoding="utf-8")
        print(f"  {member:22} {len(header + body + COMMON):6} bytes")
    print(f"\nwrote {len(BRIEFS)} authored briefs to {DST}")


if __name__ == "__main__":
    main()
